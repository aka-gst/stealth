/**
 * Уровни идут порядком, и порядок здесь — половина игры.
 *
 * Механика, которую не объяснили, читается как несправедливость, а не как
 * вызов: игрок не знает, что его выдало, и потому ничему не учится. Поэтому
 * первая комната пустая, во второй один неподвижный часовой, и дальше по
 * одному правилу за уровень. Следы, тревога, стрельба и монеты включаются
 * тогда, когда уже понятно, зачем они, — за это отвечает `rules` у каждого
 * уровня.
 *
 * Легенда карты: # стена, = ящик (не пройти, за ним прячут тела),
 * «,» высокая трава (прячет), «:» гравий (шагом по нему нельзя — слышно),
 * «-» мягкая земля и снег (шаг тихий, но остаются следы), X выход.
 */

