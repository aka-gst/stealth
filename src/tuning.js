/**
 * Сколько мира видно. Постоянна не форма кадра, а его площадь: на телефоне
 * в портрете кадр высокий и узкий, на столе широкий, но пикселей мира
 * поровну. Иначе одни игроки замечают патруль на два тайла раньше других,
 * и это уже не разные экраны, а разная игра.
 *
 * 640×360 — это 26×15 тайлов: в кадр целиком помещается двор с двумя
 * маршрутами. Меньше нельзя — стелс без обзора превращается в угадайку.
 */
export const VIEW = { w: 640, h: 360 };
const VIEW_AREA = 640 * 360;

export function fitView(cssWidth, cssHeight) {
    if (!(cssWidth > 0) || !(cssHeight > 0)) return VIEW;
    const aspect = cssWidth / cssHeight;
    const clamp = (lo, v, hi) => Math.min(hi, Math.max(lo, v));
    VIEW.w = clamp(360, Math.round(Math.sqrt(VIEW_AREA * aspect)), 820);
    VIEW.h = clamp(260, Math.round(VIEW_AREA / VIEW.w), 700);
    return VIEW;
}

