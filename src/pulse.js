/**
 * Обезличенный счётчик.
 *
 * Тот же Umami, что на главной сайта и на остальных играх: без кук, без
 * профилей, без идентификаторов человека. Отправляется только то, по чему
 * видно, где игра теряет людей: до какой комнаты доходят, за сколько, и
 * доходит ли кто-нибудь до утра.
 *
 * Событие «game-open» отсюда НЕ шлётся: его уже шлёт карточка игры на
 * главной, у всех девяти игр одинаково. Продублировать его здесь значит
 * посчитать один заход дважды и испортить сравнение между играми.
 *
 * Счётчик не должен ломать игру: если его заблокировали расширением или он
 * не загрузился, все вызовы молча ничего не делают.
 */

function send(event, data) {
    try {
        if (typeof window.umami?.track === 'function') window.umami.track(event, data);
    } catch { /* счётчик не должен ломать игру */ }
}

export const pulse = {
    /** Заход в комнату: точка, от которой считается всё остальное. */
    roomStarted(index, name) {
        send('room-start', { room: index + 1, name });
    },

    /** Комната сдана: видно, где люди застревают и сколько это стоит времени. */
    roomDone(index, name, seconds, rank) {
        send('room-done', { room: index + 1, name, seconds: Math.round(seconds), rank });
    },

    /** Провал: та же комната, но с другой стороны. */
    roomFailed(index, name, seconds) {
        send('room-failed', { room: index + 1, name, seconds: Math.round(seconds) });
    },

    /**
     * Утро. Единственное место, где считаются убитые, — и считаются числом
     * без имён: сколько людей не вышло на смену за прохождение.
     */
    escaped(killed, downed, spared) {
        send('escape-end', { killed, downed, spared });
    },
};
